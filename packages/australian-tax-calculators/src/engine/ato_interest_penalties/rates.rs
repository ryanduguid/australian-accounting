/// The penalty unit from each day, in dollars: the ATO's 'Penalty units'
/// (QC71196, last updated 26 June 2026), under Crimes Act 1914 s 4AA. The
/// table's first row, $110 up to 27 December 2012, has no start, so days
/// before 28 December 2012 are not taken.
pub(super) const PENALTY_UNITS: [(&str, u32); 8] = [
    ("2012-12-28", 170),
    ("2015-07-31", 180),
    ("2017-07-01", 210),
    ("2020-07-01", 222),
    ("2023-01-01", 275),
    ("2023-07-01", 313),
    ("2024-11-07", 330),
    ("2026-07-01", 364),
];

/// The value of `table` on `day`: the row with the latest start on or before
/// it, if any, and never after `end`.
fn on(table: &[(&str, u32)], day: i64, end: Option<i64>) -> Option<u32> {
    if end.is_some_and(|last| day > last) {
        return None;
    }
    table
        .iter()
        .rev()
        .find(|(start, _)| dates::parse(start).expect("table date") <= day)
        .map(|(_, value)| *value)
}

pub(super) fn table_end() -> i64 {
    dates::parse(TABLE_END).expect("table end")
}

pub(super) fn first_day(table: &[(&str, u32)]) -> i64 {
    dates::parse(table[0].0).expect("table date")
}

/// The annual rate in hundredths of 1% for `day`, if published.
pub(super) fn gic(day: i64) -> Option<u32> {
    on(&GIC, day, Some(table_end()))
}

pub(super) fn sic(day: i64) -> Option<u32> {
    on(&SIC, day, Some(table_end()))
}

pub(super) fn base(day: i64) -> Option<u32> {
    gic(day).map(|rate| rate - GIC_UPLIFT)
}

/// The penalty unit in dollars on `day`, if the table gives one.
pub(super) fn penalty_unit(day: i64) -> Option<u32> {
    on(&PENALTY_UNITS, day, None)
}
