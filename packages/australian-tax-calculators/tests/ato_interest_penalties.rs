//! ATO penalties and interest (TAA 1953 ss 8AAC, 8AAD and Sch 1 Divs 280, 284
//! and 286; Taxation (Interest on Overpayments and Early Payments) Act 1983)
//! on the site's GIC oracle, the ATO's and the practice statements' examples
//! and hand-worked cases on the rates read on 22 November 2026
//! (docs/calculation-evidence.md#ato-penalties-and-interest).
use australian_tax_calculators::api;
use serde_json::{Value, json};

const COMMAND: &str = "ato-interest-penalties";

fn input(question: &str, year: &str, facts: Value) -> Value {
    let mut out = facts;
    out["question"] = json!(question);
    out["year"] = json!(year);
    out["scope_confirmed"] = json!(true);
    out
}

fn run(question: &str, year: &str, facts: Value) -> Value {
    api::evaluate(COMMAND, &input(question, year, facts)).unwrap()
}

fn code(question: &str, year: &str, facts: Value) -> &'static str {
    api::evaluate_coded(COMMAND, &input(question, year, facts))
        .unwrap_err()
        .code
}

fn amount<'a>(result: &'a Value, key: &str) -> &'a str {
    result["amounts"][key].as_str().unwrap()
}

fn pays(days: &[&str], each: &str) -> Value {
    Value::Array(
        days.iter()
            .map(|day| json!({"date": day, "amount": each}))
            .collect(),
    )
}

fn gic(amount: &str, due: &str, to: &str, payments: Value) -> Value {
    json!({"amount": amount, "due_date": due, "to": to, "payments": payments})
}

/// The site's `gic-payment-plan` cases (`_data/calculator_cases.json`): a
/// plan's final instalment is the balance the day before it, and its GIC the
/// total paid less the debt.
#[test]
fn gic_agrees_with_the_sites_published_payment_plans() {
    let cases = [
        (
            "2026-27",
            "1000.00",
            "2026-10-01",
            "2026-11-30",
            pays(&["2026-10-01", "2026-11-01"], "336.56"),
            "336.56",
            "9.68",
        ),
        (
            "2026-27",
            "2500.00",
            "2026-08-20",
            "2026-08-20",
            pays(&["2026-08-20"], "2500.00"),
            "0.00",
            "0.00",
        ),
        (
            "2026-27",
            "5000.00",
            "2026-09-17",
            "2026-10-07",
            pays(&["2026-09-17", "2026-09-24", "2026-10-01"], "1254.11"),
            "1254.14",
            "16.47",
        ),
        (
            "2023-24",
            "10000.00",
            "2024-01-31",
            "2024-03-30",
            pays(&["2024-01-31", "2024-02-29"], "3364.12"),
            "3364.12",
            "92.36",
        ),
        (
            "2025-26",
            "3000.00",
            "2025-12-18",
            "2026-01-14",
            pays(&["2025-12-18", "2026-01-01"], "1004.07"),
            "1004.09",
            "12.23",
        ),
        (
            "2026-27",
            "1000000.00",
            "2026-09-30",
            "2026-10-06",
            pays(&["2026-09-30"], "500551.21"),
            "500551.22",
            "1102.43",
        ),
    ];
    for (year, debt, due, to, payments, balance, charge) in cases {
        let r = run("gic", year, gic(debt, due, to, payments));
        assert_eq!(amount(&r, "balance"), balance, "{due}");
        assert_eq!(amount(&r, "gic"), charge, "{due}");
        assert_eq!(r["assumed_days"], json!(0), "{due}");
    }
    // 12 monthly instalments from 15 November 2026: 287 days after the
    // published quarters, at 11.51% and at 9%.
    let days: Vec<String> = (0..11)
        .map(|k| {
            let (y, m) = (2026 + (10 + k) / 12, (10 + k) % 12 + 1);
            format!("{y}-{m:02}-15")
        })
        .collect();
    let days: Vec<&str> = days.iter().map(String::as_str).collect();
    for (rate, each, balance, charge) in [
        ("11.51", "1755.63", "1755.66", "1067.59"),
        ("9", "1740.95", "1740.98", "891.43"),
    ] {
        let mut facts = gic("20000.00", "2026-11-15", "2027-10-14", pays(&days, each));
        facts["assumed_annual_rate"] = json!(rate);
        let r = run("gic", "2027-28", facts);
        assert_eq!(
            (amount(&r, "balance"), amount(&r, "gic")),
            (balance, charge),
            "{rate}"
        );
        assert_eq!(r["assumed_days"], json!(287));
    }
}

/// The site oracle's seeded plans (`scripts/tests/calculator_oracle.rs`,
/// seed 0x2026_1115_061C_8AAC) whose last GIC day falls in 2020-21 to
/// 2027-28, generated by a port of `gic_case` and `gic_oracle` that
/// reproduces the oracle's hand-worked plan and its 8 published cases.
#[test]
fn gic_agrees_with_the_sites_seeded_oracle_plans() {
    let cases: Vec<Value> =
        serde_json::from_str(include_str!("data/gic_oracle_cases.json")).unwrap();
    assert_eq!(cases.len(), 36);
    for case in &cases {
        let mut facts = gic(
            case["amount"].as_str().unwrap(),
            case["due_date"].as_str().unwrap(),
            case["to"].as_str().unwrap(),
            case["payments"].clone(),
        );
        facts["assumed_annual_rate"] = case["assumed_annual_rate"].clone();
        let r = run("gic", case["year"].as_str().unwrap(), facts);
        let index = &case["seed_index"];
        assert_eq!(amount(&r, "balance"), case["balance"], "case {index}");
        assert_eq!(amount(&r, "gic"), case["gic"], "case {index}");
        assert_eq!(r["assumed_days"], case["assumed_days"], "case {index}");
    }
}

/// $10,000 unpaid from 21 November 2025 to 30 June 2026, at 10.61%, 10.65%
/// and 10.96%, compounding daily: $676.86 (hand-worked in exact fractions).
#[test]
fn gic_compounds_daily_across_quarters() {
    let r = run(
        "gic",
        "2025-26",
        json!({"amount": "10000.00", "due_date": "2025-11-21", "to": "2026-06-30"}),
    );
    assert_eq!(amount(&r, "gic"), "676.86");
    assert_eq!(amount(&r, "balance"), "10676.86");
    assert_eq!(r["days"], json!(222));
    let rates: Vec<&str> = r["stretches"]
        .as_array()
        .unwrap()
        .iter()
        .map(|s| s["annual_rate_percent"].as_str().unwrap())
        .collect();
    assert_eq!(rates, ["10.61", "10.65", "10.96"]);
}

/// Every published quarter boundary from 1 July 2020: a day either side takes
/// each quarter's own rate (11.51% from 1 October 2026, 11.43% before).
#[test]
fn gic_takes_each_quarters_rate_at_its_boundary() {
    let r = run(
        "gic",
        "2026-27",
        json!({"amount": "1000000.00", "due_date": "2026-09-30", "to": "2026-10-01"}),
    );
    let stretches = r["stretches"].as_array().unwrap();
    assert_eq!(stretches[0]["annual_rate_percent"], "11.43");
    assert_eq!(stretches[1]["annual_rate_percent"], "11.51");
    // 1,000,000 x (1 + 0.1143/365) x (1 + 0.1151/365) - 1,000,000.
    assert_eq!(amount(&r, "gic"), "628.59");
}

#[test]
fn gic_refuses_days_without_a_rate_and_bad_payments() {
    let after = json!({"amount": "100.00", "due_date": "2026-12-01", "to": "2027-01-01"});
    assert_eq!(
        code("gic", "2026-27", after),
        "ato_interest_penalties.rate_unpublished"
    );
    let early = json!({"amount": "100.00", "due_date": "1999-06-30", "to": "2020-07-01"});
    assert_eq!(
        code("gic", "2020-21", early),
        "ato_interest_penalties.rate_unpublished"
    );
    let over = gic(
        "100.00",
        "2025-07-01",
        "2025-07-10",
        pays(&["2025-07-02"], "100.10"),
    );
    assert_eq!(
        code("gic", "2025-26", over),
        "ato_interest_penalties.overpaid"
    );
    let outside = gic(
        "100.00",
        "2025-07-01",
        "2025-07-10",
        pays(&["2025-07-11"], "10.00"),
    );
    assert_eq!(
        code("gic", "2025-26", outside),
        "ato_interest_penalties.date_order"
    );
    let wrong_year = json!({"amount": "100.00", "due_date": "2025-07-01", "to": "2025-07-10"});
    assert_eq!(
        code("gic", "2024-25", wrong_year),
        "ato_interest_penalties.year_mismatch"
    );
}

fn sic(amount: &str, due: &str, notice: &str) -> Value {
    json!({"amount": amount, "due_date": due, "notice_date": notice})
}

/// TAA Sch 1 ss 280-100 and 280-105: from the first assessment's due day to
/// the day before the amended notice, at the published SIC rates (hand-worked
/// in exact fractions). PS LA 2006/8 Example 1's period, 21 November to the
/// day before a 20 March notice, moved to 2023-24.
#[test]
fn sic_runs_from_the_due_day_to_the_day_before_the_notice() {
    for (year, case, charge, days, last) in [
        (
            "2025-26",
            sic("10000.00", "2024-11-21", "2025-09-01"),
            "575.45",
            284,
            "2025-08-31",
        ),
        (
            "2023-24",
            sic("125.00", "2023-11-21", "2024-03-20"),
            "3.03",
            120,
            "2024-03-19",
        ),
        (
            "2024-25",
            sic("819.00", "2023-12-01", "2024-09-02"),
            "46.60",
            276,
            "2024-09-01",
        ),
    ] {
        let r = run("sic", year, case);
        assert_eq!(amount(&r, "sic"), charge);
        assert_eq!(
            (r["days"].clone(), r["last_day"].clone()),
            (json!(days), json!(last))
        );
    }
    // A notice on the due day leaves no day of SIC.
    let r = run("sic", "2025-26", sic("500.00", "2025-11-21", "2025-11-21"));
    assert_eq!(amount(&r, "sic"), "0.00");
    let late = sic("500.00", "2026-11-21", "2027-01-05");
    assert_eq!(
        code("sic", "2026-27", late),
        "ato_interest_penalties.rate_unpublished"
    );
}

fn ftl(due: &str, given: &str, size: &str) -> Value {
    json!({"due_date": due, "given_on": given, "size": size})
}

/// TAA Sch 1 s 286-80's example (31 days late is 2 units), the ATO's
/// significant global entity table for forms due from 1 July 2026, each
/// 28-day boundary, the 5-unit cap and the unit at each period's start.
#[test]
fn failure_to_lodge_counts_28_day_periods_at_their_penalty_unit() {
    let r = run(
        "failure_to_lodge",
        "2025-26",
        ftl("2025-10-31", "2025-12-01", "small"),
    );
    assert_eq!(
        (r["days_late"].clone(), r["penalty_units"].clone()),
        (json!(31), json!(2))
    );
    assert_eq!(amount(&r, "penalty"), "660.00");
    for (late, given_on, penalty) in [
        (1, "2026-07-16", "182000.00"),
        (28, "2026-08-12", "182000.00"),
        (29, "2026-08-13", "364000.00"),
        (56, "2026-09-09", "364000.00"),
        (57, "2026-09-10", "546000.00"),
        (84, "2026-10-07", "546000.00"),
        (85, "2026-10-08", "728000.00"),
        (112, "2026-11-04", "728000.00"),
        (113, "2026-11-05", "910000.00"),
        (300, "2027-05-11", "910000.00"),
    ] {
        let r = run(
            "failure_to_lodge",
            "2026-27",
            ftl("2026-07-15", given_on, "significant_global"),
        );
        assert_eq!(r["days_late"], json!(late), "{late}");
        assert_eq!(amount(&r, "penalty"), penalty, "{late}");
    }
    let on_time = run(
        "failure_to_lodge",
        "2025-26",
        ftl("2025-10-31", "2025-10-31", "small"),
    );
    assert_eq!(amount(&on_time, "penalty"), "0.00");
    // $330 from 10 June 2026 and $364 from 8 July 2026, doubled.
    let r = run(
        "failure_to_lodge",
        "2026-27",
        ftl("2026-06-10", "2026-08-01", "medium"),
    );
    assert_eq!(amount(&r, "base_penalty_amount"), "694.00");
    assert_eq!(amount(&r, "penalty"), "1388.00");
    // $313 from 28 October 2024, then $330 from 25 November and 23 December.
    let r = run(
        "failure_to_lodge",
        "2024-25",
        ftl("2024-10-28", "2024-12-31", "large"),
    );
    assert_eq!(amount(&r, "penalty"), "4865.00");
    let r = run(
        "failure_to_lodge",
        "2026-27",
        ftl("2025-07-31", "2026-07-31", "small"),
    );
    assert_eq!(
        (r["penalty_units"].clone(), amount(&r, "penalty")),
        (json!(5), "1650.00")
    );
    // $222 from 1 July 2020 and $275 from 1 January 2023.
    let r = run(
        "failure_to_lodge",
        "2022-23",
        ftl("2022-12-20", "2023-01-20", "small"),
    );
    assert_eq!(amount(&r, "penalty"), "497.00");
}

