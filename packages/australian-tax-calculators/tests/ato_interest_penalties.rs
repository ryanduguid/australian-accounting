fn early(amount: &str, paid: &str, due: &str, notice: Option<&str>) -> Value {
    let mut out = json!({"amount": amount, "liability": "income_tax", "paid_on": paid, "due_date": due, "full_self_assessment": notice.is_none()});
    if let Some(day) = notice {
        out["notice_issued"] = json!(day);
    }
    out
}

/// The ATO's Evan example ('Credit interest rates and calculation'), its
/// dates moved to 2025: 3 to 21 November is 19 days, at 3.61%: $3.62. More
/// than 14 days early is required (s 8A(1)(b)); the period starts on the
/// later of the payment and the notice for one not a full self-assessment
/// taxpayer (s 8B(1)); under 50 cents is not paid (s 12E).
#[test]
fn early_payment_interest_follows_sections_8a_to_8c() {
    let r = run(
        "early_payment_interest",
        "2025-26",
        early("1926.00", "2025-11-03", "2025-11-21", Some("2025-10-29")),
    );
    assert_eq!(
        (r["days"].clone(), amount(&r, "interest")),
        (json!(19), "3.62")
    );
    let r = run(
        "early_payment_interest",
        "2025-26",
        early("1926.00", "2025-11-07", "2025-11-21", Some("2025-10-29")),
    );
    assert_eq!(
        (r["entitled"].clone(), amount(&r, "interest")),
        (json!(false), "0.00")
    );
    let r = run(
        "early_payment_interest",
        "2025-26",
        early("1926.00", "2025-11-06", "2025-11-21", Some("2025-10-29")),
    );
    assert_eq!(r["entitled"], json!(true));
    let r = run(
        "early_payment_interest",
        "2026-27",
        early("50000.00", "2026-06-01", "2026-07-31", None),
    );
    assert_eq!(
        (r["days"].clone(), amount(&r, "interest")),
        (json!(61), "350.86")
    );
    let r = run(
        "early_payment_interest",
        "2025-26",
        early("100.00", "2025-11-06", "2025-11-21", Some("2025-10-01")),
    );
    assert_eq!(
        (amount(&r, "interest"), amount(&r, "interest_payable")),
        ("0.16", "0.00")
    );
    let r = run(
        "early_payment_interest",
        "2025-26",
        early("5000.00", "2025-11-05", "2025-12-01", Some("2025-11-10")),
    );
    assert_eq!(
        (r["first_day"].clone(), amount(&r, "interest")),
        (json!("2025-11-10"), "10.88")
    );
    let mut gst = early("100.00", "2025-11-01", "2025-12-01", None);
    gst["liability"] = json!("gst");
    assert_eq!(
        code("early_payment_interest", "2025-26", gst),
        "ato_interest_penalties.liability_not_listed"
    );
}

fn overpaid(payments: Value, refunded: &str, on: &str) -> Value {
    json!({"payments": payments, "refunded": refunded, "refunded_on": on, "notice_issued": "2024-10-15", "relevant_tax": true, "decision_to_which_act_applies": true})
}

/// Overpayments Act ss 9 and 10: simple interest at the base rate from the
/// later of the notice and the payment to the refund day, a partial refund
/// going to the instalments in reverse order (s 9(3)).
#[test]
fn overpayment_interest_attributes_a_refund_to_the_last_instalments() {
    let one = json!([{"paid_on": "2024-11-21", "amount": "5000.00"}]);
    let r = run(
        "overpayment_interest",
        "2025-26",
        overpaid(one, "2000.00", "2025-09-30"),
    );
    assert_eq!(amount(&r, "interest"), "71.46");
    assert_eq!(r["attribution"][0]["days"], json!(314));
    let two = json!([{"paid_on": "2024-12-01", "amount": "3000.00"}, {"paid_on": "2025-03-01", "amount": "3000.00"}]);
    let r = run(
        "overpayment_interest",
        "2025-26",
        overpaid(two.clone(), "4000.00", "2025-08-15"),
    );
    assert_eq!(amount(&r, "interest"), "86.51");
    assert_eq!(r["attribution"][0]["paid_on"], "2025-03-01");
    assert_eq!(r["attribution"][1]["attributed"], "1000.00");
    assert_eq!(
        code(
            "overpayment_interest",
            "2025-26",
            overpaid(two, "6000.01", "2025-08-15")
        ),
        "ato_interest_penalties.overpaid"
    );
    let mut other = overpaid(
        json!([{"paid_on": "2024-11-21", "amount": "5000.00"}]),
        "1.00",
        "2025-09-30",
    );
    other["decision_to_which_act_applies"] = json!(false);
    assert_eq!(
        code("overpayment_interest", "2025-26", other),
        "ato_interest_penalties.not_entitled"
    );
}

/// Remission is the Commissioner's discretion and scheme penalties are not
/// worked: both are refused, never estimated.
#[test]
fn remission_and_scheme_penalties_are_refused() {
    assert_eq!(
        code("remission", "2025-26", json!({})),
        "ato_interest_penalties.remission_discretionary"
    );
    assert_eq!(
        code("scheme_penalty", "2025-26", json!({})),
        "ato_interest_penalties.scheme_penalty"
    );
    assert_eq!(
        code("penalty", "2025-26", json!({})),
        "ato_interest_penalties.question_invalid"
    );
    let r = run(
        "sic",
        "2025-26",
        sic("10000.00", "2024-11-21", "2025-09-01"),
    );
    assert!(r["remission"].as_str().unwrap().contains("s 280-160"));
}
