fn statement(date: &str, sge: bool, parts: Value) -> Value {
    json!({"statement_date": date, "significant_global_entity": sge, "parts": parts})
}

fn penalty(facts: Value) -> String {
    let year = {
        let day = facts["statement_date"].as_str().unwrap();
        let (y, m): (i64, i64) = (day[..4].parse().unwrap(), day[5..7].parse().unwrap());
        let start = if m >= 7 { y } else { y - 1 };
        format!("{start}-{:02}", (start + 1) % 100)
    };
    amount(&run("statement_penalty", &year, facts), "penalty").to_string()
}

/// MT 2008/2 Examples 1 and 2 (AJ Co and Hill Co): the not reasonably
/// arguable penalty needs a shortfall more than the greater of $10,000 and
/// 1% of the tax on the return; more than, so $10,000 exactly is not.
#[test]
fn the_reasonably_arguable_threshold_gates_item_4() {
    let part = |amount: &str| json!([{"shortfall_amount": amount, "behaviour": "reasonable_care", "not_reasonably_arguable": true}]);
    let mut aj = statement("2026-03-15", false, part("7000.00"));
    aj["income_tax_payable"] = json!("50000.00");
    assert_eq!(penalty(aj), "0.00");
    let mut hill = statement("2026-03-15", false, part("500000.00"));
    hill["income_tax_payable"] = json!("20000000.00");
    assert_eq!(penalty(hill), "125000.00");
    let mut level = statement("2026-03-15", false, part("10000.00"));
    level["income_tax_payable"] = json!("50000.00");
    assert_eq!(penalty(level), "0.00");
    let mut over = statement("2026-03-15", false, part("10000.01"));
    over["income_tax_payable"] = json!("50000.00");
    assert_eq!(penalty(over), "2500.00");
    // s 284-90(2): recklessness's 50% beats item 4's 25%.
    let mut both = statement(
        "2026-03-15",
        false,
        json!([{"shortfall_amount": "15000.00", "behaviour": "recklessness", "not_reasonably_arguable": true}]),
    );
    both["income_tax_payable"] = json!("50000.00");
    assert_eq!(penalty(both), "7500.00");
}

/// PS LA 2012/5 Example 7 (Scrooge Company): $15,000 from intentional
/// disregard and $2,000 from a failure to take reasonable care, each at its
/// own rate; MT 2012/3 paras 88 and 89 (Benton): only the $2,000 he disclosed
/// during the audit is reduced by 20% (failure to take reasonable care
/// assumed); s 284-224's accepted part; an increase; a significant global
/// entity's doubling (the ATO's SGE page: recklessness is 100%).
#[test]
fn statement_penalties_work_each_part_at_its_own_rate() {
    let scrooge = json!([
        {"shortfall_amount": "15000.00", "behaviour": "intentional_disregard"},
        {"shortfall_amount": "2000.00", "behaviour": "failure_to_take_reasonable_care"},
    ]);
    assert_eq!(penalty(statement("2026-03-15", false, scrooge)), "11750.00");
    let benton = json!([
        {"shortfall_amount": "10000.00", "behaviour": "failure_to_take_reasonable_care"},
        {"shortfall_amount": "2000.00", "behaviour": "failure_to_take_reasonable_care", "disclosure": "during_examination"},
    ]);
    assert_eq!(penalty(statement("2026-03-15", false, benton)), "2900.00");
    let accepted = json!([{"shortfall_amount": "8000.00", "behaviour": "failure_to_take_reasonable_care", "accepted_way_amount": "3000.00"}]);
    assert_eq!(penalty(statement("2026-03-15", false, accepted)), "1250.00");
    let increased =
        json!([{"shortfall_amount": "10000.00", "behaviour": "recklessness", "increase": true}]);
    assert_eq!(
        penalty(statement("2026-03-15", false, increased)),
        "6000.00"
    );
    let both = json!([{"shortfall_amount": "10000.00", "behaviour": "recklessness", "increase": true, "disclosure": "during_examination"}]);
    assert_eq!(penalty(statement("2026-03-15", false, both)), "5000.00");
    let sge = json!([{"shortfall_amount": "100000.00", "behaviour": "recklessness"}]);
    assert_eq!(penalty(statement("2026-03-15", true, sge)), "100000.00");
}

/// s 284-225(3): a disclosure before an examination is notified cuts the
/// penalty by 80% from $1,000 of shortfall, and to nil below it; the period's
/// disclosed parts are added (MT 2012/3 para 35).
#[test]
fn a_disclosure_before_examination_cuts_80_percent_or_to_nil() {
    let one = |amount: &str| json!([{"shortfall_amount": amount, "behaviour": "failure_to_take_reasonable_care", "disclosure": "before_examination"}]);
    assert_eq!(
        penalty(statement("2026-03-15", false, one("999.99"))),
        "0.00"
    );
    assert_eq!(
        penalty(statement("2026-03-15", false, one("1000.00"))),
        "50.00"
    );
    let two = json!([
        {"shortfall_amount": "600.00", "behaviour": "failure_to_take_reasonable_care", "disclosure": "before_examination"},
        {"shortfall_amount": "600.00", "behaviour": "failure_to_take_reasonable_care", "disclosure": "before_examination"},
    ]);
    assert_eq!(penalty(statement("2026-03-15", false, two)), "60.00");
    let nil_and_up = json!([{"shortfall_amount": "500.00", "behaviour": "recklessness", "increase": true, "disclosure": "before_examination"}]);
    assert_eq!(
        code(
            "statement_penalty",
            "2025-26",
            statement("2026-03-15", false, nil_and_up)
        ),
        "ato_interest_penalties.increase_with_nil"
    );
}

