"""Generate this crate's src/pyunicode.rs from CPython's Unicode data.

The Rust crates cannot read `unicodedata`, so each keeps the tables it needs as
saved data. This crate's file holds them all, and the root
tests/test_shared_blocks.py pins the other 5 crates' copies to it and compares this
script's tables with it. Run with the interpreter the header names, format with the
crate's rustfmt and compare with the committed file:

    python tools/gen_pyunicode.py > pyunicode.new.rs
    rustfmt pyunicode.new.rs

WORD_DIFF also depends on the regex crate's `\\w`, which CPython cannot report, so
it is not generated: the output holds a comment in its place. Keep the committed
table, and rebuild it by hand when the regex crate's Unicode version changes.
"""

import sys
import unicodedata

if (
    sys.implementation.name != "cpython"
    or sys.version_info[:3] != (3, 15, 0)
    or unicodedata.unidata_version != "17.0.0"
):
    raise SystemExit("Use CPython 3.15.0 with Unicode 17.0.0, matching the saved tables")


def ranges(pred):
    out, start = [], None
    for cp in range(0x110000):
        ok = pred(chr(cp))
        if ok and start is None:
            start = cp
        elif not ok and start is not None:
            out.append((start, cp - 1))
            start = None
    if start is not None:
        out.append((start, 0x10FFFF))
    return out


def fmt_ranges(name, predicate, digits="04X"):
    body = "\n".join(f"    (0x{a:{digits}}, 0x{b:{digits}})," for a, b in ranges(predicate))
    return f"pub static {name}: &[(u32, u32)] = &[\n{body}\n];\n"


def fmt_casefold():
    rows = []
    for cp in range(0x110000):
        if 0xD800 <= cp <= 0xDFFF:
            continue
        folded = chr(cp).casefold()
        if folded != chr(cp):
            escaped = "".join("\\u{%X}" % ord(x) for x in folded)
            rows.append(f'    (0x{cp:04X}, "{escaped}"),')
    return "pub static CASEFOLD: &[(u32, &str)] = &[\n" + "\n".join(rows) + "\n];\n"


def fmt_decimal_zero():
    zero = (chr(cp) for cp in range(0x110000))
    body = ", ".join(f"0x{ord(c):04X}" for c in zero if c.isdecimal() and unicodedata.decimal(c) == 0)
    return f"pub static DECIMAL_ZERO: &[u32] = &[{body}];\n"


def main():
    out = [
        "// Generated by gen_pyunicode.py from CPython "
        f"{sys.version.split()[0]} (Unicode {unicodedata.unidata_version}). Do not edit.",
        "// Tables reproduce the str predicates and mappings the original Python builder used.",
        "",
        fmt_ranges("NOT_PRINTABLE", lambda c: not c.isprintable()),
        fmt_ranges("SPACE", str.isspace),
        fmt_ranges("DECIMAL", str.isdecimal),
        # sre's `\w`: Py_UNICODE_ISALNUM or the underscore.
        fmt_ranges("WORD", lambda c: c.isalnum() or c == "_"),
        fmt_casefold(),
        "pub static IGNORECASE_EXTRA: &[(char, &[u32])] =\n"
        "    &[('i', &[0x0130, 0x0131]), ('k', &[0x212A]), ('s', &[0x017F])];\n",
        fmt_decimal_zero(),
        "// WORD_DIFF: keep the committed table; see this script's docstring.\n",
        "/// `str.isalpha()`: categories Lm, Lt, Lu, Ll and Lo.",
        fmt_ranges("ALPHA", str.isalpha, digits="x"),
    ]
    sys.stdout.buffer.write("\n".join(out).encode("utf-8"))


if __name__ == "__main__":
    main()
